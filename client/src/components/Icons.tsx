export function Avatar({ name, size = 32, avatarUrl }: { name?: string; size?: number; avatarUrl?: string }) {
  if (avatarUrl) {
    return (
      <img
        src={avatarUrl}
        alt={name || "User"}
        style={{
          width: size,
          height: size,
          borderRadius: "50%",
          objectFit: "cover",
          flexShrink: 0,
        }}
      />
    );
  }

  const initial = (name || "U").trim().charAt(0).toUpperCase();
  const colors = [
    { bg: "#282828", text: "#F1F1F1" },
    { bg: "#303030", text: "#F1F1F1" },
    { bg: "#383838", text: "#F1F1F1" },
    { bg: "#242424", text: "#F1F1F1" },
  ];
  const charCode = initial.charCodeAt(0) || 0;
  const color = colors[charCode % colors.length];

  return (
    <div
      style={{
        width: size,
        height: size,
        borderRadius: "50%",
        backgroundColor: color.bg,
        color: color.text,
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        fontWeight: 600,
        fontSize: Math.max(11, Math.round(size * 0.42)),
        flexShrink: 0,
        userSelect: "none",
      }}
    >
      {initial}
    </div>
  );
}
